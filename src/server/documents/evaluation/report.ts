/**
 * Renders evaluation results as text and JSON.
 *
 * Honesty rules, enforced here and tested in tests/eval.test.ts:
 *   - Every corpus section opens by saying, in words, what kind of corpus it is.
 *   - Synthetic and real results are reported separately. There is no overall,
 *     combined or blended figure anywhere, in the text or in the JSON.
 *   - When there are no real documents, the report says real-world accuracy is
 *     unmeasured, and prints no real-corpus figures at all.
 */
import { CLAIMED_FIELDS, LINE_AMOUNT_FIELDS } from '@/server/types';
import { accuracy, CALIBRATION_BUCKETS, HIGH_CONFIDENCE, type Miss, type Summary, type Tally } from './score';
import { gateMetrics, type CorpusKind, type CorpusResult } from './run';

export const SYNTHETIC_DISCLAIMER = "SYNTHETIC: generated by this project's own renderer. Says nothing about accuracy on real documents.";
export const NO_REAL_DOCUMENTS = 'No real documents evaluated. Real-world accuracy is unmeasured.';
export const realDisclaimer = (n: number, dir = 'eval/real') =>
  `REAL: ${n} customer document${n === 1 ? '' : 's'} from ${dir}, checked against hand-keyed truth files. These figures describe ${n === 1 ? 'this document' : `these ${n} documents`} only; the 95% intervals show how little a sample this size can say.`;

const pct = (v: number | null) => (v === null ? '   n/a' : `${(v * 100).toFixed(1).padStart(5)}%`);

/** Wilson score interval, for small samples. */
export function wilson(correct: number, n: number): [number, number] | null {
  if (n === 0) return null;
  const z = 1.96;
  const p = correct / n;
  const denom = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / denom;
  const half = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / denom;
  return [Math.max(0, centre - half), Math.min(1, centre + half)];
}

function rate(correct: number, n: number, kind: CorpusKind): string {
  const v = n === 0 ? null : correct / n;
  const base = `${pct(v)} (${correct}/${n})`;
  if (kind !== 'real' || n === 0) return base;
  const ci = wilson(correct, n)!;
  return `${base}  95% CI ${(ci[0] * 100).toFixed(0)}–${(ci[1] * 100).toFixed(0)}%`;
}

function tallyRow(label: string, t: Tally): string {
  const cols = [
    label.padEnd(30),
    String(t.n).padStart(5),
    pct(accuracy(t)).padStart(8),
    String(t.correct).padStart(8),
    String(t.abstained).padStart(9),
    String(t.flagged).padStart(8),
    String(t.wrong).padStart(10),
    `${t.absentCorrect}/${t.absentN}`.padStart(12),
    String(t.spuriousFlagged + t.spuriousWrong ? `${t.spuriousWrong}/${t.spuriousFlagged}` : '0').padStart(12),
  ];
  return cols.join('');
}
const TALLY_HEAD = ['Field'.padEnd(30), 'n'.padStart(5), 'acc'.padStart(8), 'correct'.padStart(8), 'declined'.padStart(9), 'flagged'.padStart(8), 'WRONG-HIGH'.padStart(10), 'blank ok'.padStart(12), 'invented h/l'.padStart(12)].join('');

function table(title: string, s: Summary, keys: string[], label: (k: string) => string): string[] {
  const rows = keys.filter((k) => s.fields[k]).map((k) => tallyRow(label(k), s.fields[k]!));
  if (rows.length === 0) return [];
  return [title, TALLY_HEAD, ...rows, ''];
}

const show = (v: unknown) => (v === null || v === undefined ? '—' : typeof v === 'number' ? String(v) : JSON.stringify(v));

function missLine(m: Miss): string {
  const tag = m.bucket === 'wrong' ? 'WRONG-HIGH' : m.bucket === 'flagged' ? 'flagged' : m.bucket === 'abstained' ? (m.expectedAbstain ? 'declined (expected)' : 'declined') : 'unmet';
  const conf = m.confidence === null ? '' : ` conf ${m.confidence.toFixed(2)}`;
  return `  [${tag}] ${m.caseId} :: ${m.path}  expected ${show(m.expected)}  got ${show(m.actual)}${conf}${m.limitation ? '  (known limitation)' : ''}`;
}

export function renderCorpus(result: CorpusResult, opts: { verbose?: boolean; realDir?: string } = {}): string {
  const s = result.summary;
  const kind = result.kind;
  const out: string[] = [];
  const engineLabel = result.engine === 'claude' ? `claude (${result.model})` : result.engine === 'auto' ? `auto${result.model ? ` (claude: ${result.model})` : ' (text-layer: no API key)'}` : 'text-layer';
  out.push('='.repeat(100));
  out.push(`${kind.toUpperCase()} CORPUS · engine: ${engineLabel}`);
  out.push(kind === 'synthetic' ? SYNTHETIC_DISCLAIMER : realDisclaimer(s.cases, opts.realDir));
  out.push('='.repeat(100));
  out.push(`Files: ${s.cases}   Pages: ${s.pages}   Outcome as expected: ${s.outcomesMet}/${s.cases}   (${Object.entries(s.outcomes).map(([k, v]) => `${k} ${v}`).join(', ')})`);
  if (result.excluded.length) out.push(`Left out (not scored): ${result.excluded.length}. ${result.excluded.map((e) => `${e.caseId}: ${e.reason}`).join('; ')}`);
  out.push('');
  out.push(`CONFIDENTLY WRONG (wrong value at confidence >= ${HIGH_CONFIDENCE}, so nothing asks a person to check it): ${s.confidentlyWrong}`);
  out.push(`Safe misses: ${s.safe.flagged} wrong but flagged for review, ${s.safe.abstained} declined (left blank for a person).`);
  out.push('');
  const g = s.groups;
  out.push('Summary (share of values present on the documents that were read exactly right):');
  out.push(`  Document type, per page     ${rate(g.pageType.correct, g.pageType.n, kind)}`);
  out.push(`  G702 amounts, to the cent   ${rate(g.header.correct, g.header.n, kind)}`);
  out.push(`  G702 identifying fields     ${rate(g.identity.correct, g.identity.n, kind)}`);
  out.push(`  Schedule rows found         recall ${rate(s.rows.matched, s.rows.expected, kind)}   precision ${rate(s.rows.matched, s.rows.read, kind)}`);
  out.push(`  Schedule cells              ${rate(g.line.correct, g.line.n, kind)}`);
  out.push(`  Schedule grand totals       ${rate(g.lineTotal.correct, g.lineTotal.n, kind)}`);
  out.push(`  Lien waiver fields          ${rate(g.waiver.correct, g.waiver.n, kind)}`);
  out.push(`  Expected flags raised       ${rate(s.flags.met, s.flags.expected, kind)}   (conflicts reported that the truth does not expect: ${s.unexpectedConflicts})`);
  out.push(`  Expected notes present      ${rate(s.notePatterns.met, s.notePatterns.expected, kind)}`);
  out.push('');
  out.push('Columns: n = values present on the documents; declined = reader gave none (safe); flagged = wrong but below the');
  out.push(`review threshold (safe); WRONG-HIGH = wrong at confidence >= ${HIGH_CONFIDENCE} (dangerous); blank ok = not printed and`);
  out.push('correctly left empty; invented h/l = a value reported where none is printed, at high / low confidence.');
  out.push('');
  out.push(...table('Document type', s, ['pageType.page'], () => 'page'));
  out.push(...table('G702 amounts', s, CLAIMED_FIELDS.map((f) => `header.${f}`), (k) => k.slice(7)));
  out.push(...table('G702 identifying fields', s, ['applicationNumber', 'periodTo', 'applicationDate', 'projectName', 'projectNumber', 'contractorName', 'toName', 'contractNumber', 'contractDate', 'signed', 'notarized'].map((f) => `identity.${f}`), (k) => k.slice(9)));
  out.push(...table('Schedule of values (per column; unmatched rows count as declined)', s, ['row', 'itemNo', 'description', ...LINE_AMOUNT_FIELDS].map((f) => `line.${f}`), (k) => k.slice(5)));
  out.push(...table('Schedule grand-total row', s, LINE_AMOUNT_FIELDS.map((f) => `lineTotal.${f}`), (k) => k.slice(10)));
  out.push(...table('Lien waivers', s, ['waiver', 'waiverType', 'formState', 'claimant', 'customer', 'owner', 'throughDate', 'amount', 'exceptions', 'signed'].map((f) => `waiver.${f}`), (k) => k.slice(7)));
  out.push('Confidence calibration (values reported, by stated confidence):');
  s.calibration.forEach((b, i) => {
    const [from, to] = CALIBRATION_BUCKETS[i]!;
    out.push(`  ${from.toFixed(2)}–${Math.min(1, to).toFixed(2)}  reported ${String(b.reported).padStart(5)}  correct ${rate(b.correct, b.reported, kind)}`);
  });
  out.push('');
  const dangerous = s.misses.filter((m) => m.bucket === 'wrong');
  out.push(`Confidently wrong values (${dangerous.length}):`);
  out.push(...(dangerous.length ? dangerous.map(missLine) : ['  none']));
  out.push('');
  const unmet = s.misses.filter((m) => m.bucket === 'unmet');
  out.push(`Expectations not met (${unmet.length}):`);
  out.push(...(unmet.length ? unmet.map(missLine) : ['  none']));
  out.push('');
  const rest = s.misses.filter((m) => m.bucket === 'flagged' || m.bucket === 'abstained');
  out.push(`Every other miss (${rest.length}: flagged or declined):`);
  if (opts.verbose || rest.length <= 400) out.push(...(rest.length ? rest.map(missLine) : ['  none']));
  else out.push(`  ${rest.length} misses; run with --verbose or --json to list them all.`);
  if (opts.verbose) {
    out.push('');
    out.push('Per file:');
    for (const c of result.scored) {
      const wrong = c.items.filter((i) => i.bucket === 'wrong').length;
      const ok = c.items.filter((i) => i.bucket === 'correct').length;
      out.push(`  ${c.caseId}  [${c.status}${c.outcomeMet ? '' : ` ≠ expected ${c.expectedOutcome}`}]  ${ok}/${c.items.length} correct, ${wrong} wrong-high, ${c.durationMs} ms`);
      for (const n of c.notes) out.push(`      note: ${n}`);
    }
  }
  out.push('');
  return out.join('\n');
}

export function renderReport(input: { synthetic?: CorpusResult[]; real?: CorpusResult[]; realRequested: boolean; realDir: string; realSkipped?: string[]; realErrors?: string[]; gate?: string[]; header: string }, opts: { verbose?: boolean } = {}): string {
  const out: string[] = [input.header, ''];
  for (const r of input.synthetic ?? []) out.push(renderCorpus(r, opts));
  if (input.realRequested) {
    const real = (input.real ?? []).filter((r) => r.scored.length > 0 || r.excluded.length > 0);
    if (real.length === 0) {
      out.push('='.repeat(100));
      out.push('REAL CORPUS');
      out.push(NO_REAL_DOCUMENTS);
      out.push(`(Looked in ${input.realDir}. See docs/extraction-evaluation.md for how to add documents.)`);
      out.push('='.repeat(100));
      out.push('');
    } else {
      for (const r of real) out.push(renderCorpus(r, { ...opts, realDir: input.realDir }));
    }
    if (input.realSkipped?.length) out.push(`Documents in ${input.realDir} with no truth file (not evaluated): ${input.realSkipped.join(', ')}`);
    if (input.realErrors?.length) out.push(`Problems in ${input.realDir}:\n${input.realErrors.map((e) => `  ${e}`).join('\n')}`);
  }
  if (input.gate) {
    out.push('Synthetic regression gate: ' + (input.gate.length === 0 ? 'passed.' : `FAILED\n${input.gate.map((g) => `  - ${g}`).join('\n')}`));
  }
  return out.join('\n');
}

/** JSON output. Each corpus stands alone; there is deliberately no top-level metric. */
export function reportJson(input: { synthetic?: CorpusResult[]; real?: CorpusResult[]; realRequested: boolean; meta: Record<string, unknown>; gate?: string[] }) {
  const corpus = (r: CorpusResult) => ({
    kind: r.kind,
    disclaimer: r.kind === 'synthetic' ? SYNTHETIC_DISCLAIMER : realDisclaimer(r.summary.cases),
    engine: r.engine,
    model: r.model,
    metrics: gateMetrics(r.summary),
    summary: r.summary,
    excluded: r.excluded,
    files: r.scored.map((c) => ({ caseId: c.caseId, file: c.file, engine: c.engine, status: c.status, expectedOutcome: c.expectedOutcome, rows: c.rows, flags: c.flags, notePatterns: c.notePatterns, unexpectedConflicts: c.unexpectedConflicts, knownLimitation: c.knownLimitation, notes: c.notes })),
  });
  const real = (input.real ?? []).filter((r) => r.scored.length > 0 || r.excluded.length > 0);
  return {
    meta: input.meta,
    corpora: [...(input.synthetic ?? []).map(corpus), ...real.map(corpus)],
    ...(input.realRequested && real.length === 0 ? { real: NO_REAL_DOCUMENTS } : {}),
    ...(input.gate ? { gate: { passed: input.gate.length === 0, breaches: input.gate } } : {}),
  };
}
